import { confirmDestructive, confirmUserData, CONFIRM_FLAG, USER_DATA_FLAG } from "../confirm";

// push.ts opens with "truncate test_centres, manoeuvres, show_me_tell_me
// restart identity cascade" against whatever database the environment happens
// to point at. Cascade reaches routes and hazards. The only thing between a
// stale PGHOST and an emptied production table was remembering which shell you
// were in.

test("without the flag it refuses, and says what it would have destroyed", () => {
  const refusal = confirmDestructive([], { PGHOST: "db.prod.supabase.co" });

  expect(refusal).not.toBeNull();
  expect(refusal).toContain("db.prod.supabase.co");
  expect(refusal).toContain(CONFIRM_FLAG);
});

test("with the flag it goes ahead", () => {
  expect(confirmDestructive([CONFIRM_FLAG], { PGHOST: "db.prod.supabase.co" })).toBeNull();
});

// A connection string on argv is the other way credentials arrive, and the
// host inside it is the thing worth reading back before saying yes.
test("the host is read out of a connection string too", () => {
  const refusal = confirmDestructive(["postgresql://u:p@aws-0-eu-west-1.pooler.supabase.com:5432/postgres"], {});

  expect(refusal).toContain("aws-0-eu-west-1.pooler.supabase.com");
});

// A password in a connection string must not be echoed back at the person by
// the very message telling them to be careful.
test("the refusal never repeats the password back", () => {
  const refusal = confirmDestructive(["postgresql://postgres:hunter2secret@host:5432/postgres"], {});

  expect(refusal).not.toContain("hunter2secret");
});

test("an unknown target still names something rather than nothing", () => {
  expect(confirmDestructive([], {})).toContain("unknown");
});

// ── The cascade's blast radius ────────────────────────────────────────────
//
// --yes-truncate only ever asked "is this the right host". It never asked the
// question that actually costs something, which is what else goes with it.
//
// TRUNCATE ... CASCADE does not consult ON DELETE clauses. It truncates every
// table with a foreign key into the targets, whatever those clauses say. Here
// that is user_progress and favourites: every mock test anybody has driven and
// every centre they saved. Route ids are regenerated by each seed run anyway,
// so the rows could not have survived meaningfully even if they were spared.
//
// The common case is that those tables are empty, and that case must stay a
// single flag. The expensive case is the one that has to be looked at.

test("empty user tables need no second flag", () => {
  expect(confirmUserData({ user_progress: 0, favourites: 0 }, [CONFIRM_FLAG])).toBeNull();
});

test("rows anybody would miss stop the run and are counted out by table", () => {
  const refusal = confirmUserData({ user_progress: 42, favourites: 7 }, [CONFIRM_FLAG]);

  expect(refusal).not.toBeNull();
  expect(refusal).toContain("user_progress");
  expect(refusal).toContain("42");
  expect(refusal).toContain("favourites");
  expect(refusal).toContain("7");
  expect(refusal).toContain(USER_DATA_FLAG);
});

// A table that is already empty is noise in a warning about what is not.
test("only the tables that would actually lose something are listed", () => {
  const refusal = confirmUserData({ user_progress: 3, favourites: 0 }, [CONFIRM_FLAG]);

  expect(refusal).toContain("user_progress");
  expect(refusal).not.toContain("favourites");
});

test("the second flag lets it through, having been looked at", () => {
  expect(
    confirmUserData({ user_progress: 42, favourites: 7 }, [CONFIRM_FLAG, USER_DATA_FLAG])
  ).toBeNull();
});

// The two flags are independent. Acknowledging the user data does not
// acknowledge the host, which is the thing the first flag is for.
test("the user-data flag alone does not stand in for the host confirmation", () => {
  expect(confirmDestructive([USER_DATA_FLAG], { PGHOST: "db.prod.supabase.co" })).not.toBeNull();
});
